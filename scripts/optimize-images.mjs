import { execFileSync } from 'node:child_process';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Optional authoring tool: install libwebp (cwebp). Generated assets are committed,
// so development and production builds still require only Node.js.
const root = new URL('../', import.meta.url);
const output = new URL('assets/images/', root);
const portraitSizes = '(max-width: 767px) min(calc(78vw - 37px), 350px), (max-width: 1024px) 31vw, (max-width: 1600px) 28vw, 435px';
const phoneSizes = 'auto, (max-width: 767px) 224px, (max-width: 1280px) 278px, (max-width: 1600px) 20vw, 307px';
const medstorySizes = 'auto, (max-width: 767px) 224px, (max-width: 1024px) 158px, (max-width: 1435px) calc(17vw - 16px), 228px';
const images = [
  ['portrait', [320, 480, 640, 960], portraitSizes, 82],
  ['streaming-tv', [480, 960, 1248], 'auto, (max-width: 479px) calc(100vw - 58px), (max-width: 767px) calc(100vw - 196px), (max-width: 1600px) 69vw, 1106px'],
  ['streaming-mobile', [180, 360], 'auto, 214px'],
  ['streaming-catalog', [480, 960, 1440, 1920], 'auto, (max-width: 767px) calc(100vw - 58px), (max-width: 1600px) 64vw, 930px'],
  ['leclick-discover', [240, 480, 785], phoneSizes],
  ['leclick-map', [240, 480, 852], phoneSizes],
  ['leclick-bookings', [240, 480, 853], phoneSizes],
  ...['capture', 'timeline', 'detail', 'search', 'visit'].map(name => [`medstory-${name}`, [240, 480, 720], medstorySizes]),
  ['crypto-app', [480, 960, 1440], 'auto, (max-width: 767px) min(calc(100vw - 58px), 470px), (max-width: 1600px) 36vw, 520px'],
];

await mkdir(output, { recursive: true });
let html = await readFile(new URL('index.html', root), 'utf8');
const previews = ['/* Generated by npm run images. Preview backgrounds remain visible while images load, without JavaScript. */', '.image-preview{background-image:var(--image-preview);background-size:100% 100%;background-repeat:no-repeat}'];
let originalBytes = 0;
let largestBytes = 0;
for (const [name, widths, sizes, quality = 90] of images) {
  const source = new URL(`assets/${name}.png`, root);
  originalBytes += (await stat(source)).size;
  const png = await readFile(source);
  const originalWidth = png.readUInt32BE(16);
  const originalHeight = png.readUInt32BE(20);
  for (const width of widths) {
    if (width > originalWidth) throw new Error(`Refusing to upscale ${name} to ${width}px`);
    execFileSync('cwebp', ['-quiet', '-q', String(quality), '-m', '6', '-sharp_yuv', '-resize', String(width), '0', fileURLToPath(source), '-o', fileURLToPath(new URL(`${name}-${width}.webp`, output))]);
  }
  largestBytes += (await stat(new URL(`${name}-${widths.at(-1)}.webp`, output))).size;
  // Tiny, low-quality WebP previews are embedded in CSS: no extra image requests.
  const preview = execFileSync('cwebp', ['-quiet', '-q', '30', '-resize', '24', '0', fileURLToPath(source), '-o', '-']);
  previews.push(`[data-image="${name}"]{--image-preview:url("data:image/webp;base64,${preview.toString('base64')}")}`);
  const srcset = widths.map(width => `assets/images/${name}-${width}.webp ${width}w`).join(', ');
  const defaultWidth = widths.includes(480) ? 480 : widths.at(-1);
  let found = false;
  html = html.replace(/<img\b[^>]*>/g, tag => {
    if (!tag.includes(`assets/${name}.png`) && !tag.includes(`data-image="${name}"`)) return tag;
    found = true;
    const clean = tag.replace(/\s(?:src|srcset|sizes|data-image)="[^"]*"/g, '')
      .replace(/width="\d+"/, `width="${originalWidth}"`)
      .replace(/height="\d+"/, `height="${originalHeight}"`)
      .replace(/class="([^"]*)"/, (_, classes) => `class="${classes.split(' ').filter(c => c !== 'image-preview').join(' ')} image-preview"`);
    return clean.replace('<img ', `<img src="assets/images/${name}-${defaultWidth}.webp" srcset="${srcset}" sizes="${sizes}" data-image="${name}" `);
  });
  if (!found) throw new Error(`No image found in index.html for ${name}`);
}
await writeFile(new URL('index.html', root), html);
await writeFile(new URL('assets/image-previews.css', root), previews.join('\n') + '\n');
console.log(`Generated ${images.length} responsive images and embedded previews. Originals: ${(originalBytes / 1024 / 1024).toFixed(2)} MiB; largest WebP variants: ${(largestBytes / 1024 / 1024).toFixed(2)} MiB.`);
